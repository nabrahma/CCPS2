"""Licence manifest: every shipped file gets one row (PRD rule 5)."""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field

from .paths import ASSETS_CORE, COMPILER_DIR

# Art and data: CC0 or CC-BY. Bundled runtime software (MediaPipe): Apache-2.0 with its notice.
ALLOWED = {"CC0-1.0", "CC-BY-4.0", "CC-BY-3.0", "Apache-2.0"}


@dataclass
class LicenseCollector:
    rows: dict[str, dict] = field(default_factory=dict)

    def add(self, file: str, asset_id: str, licence: str, author: str, source_url: str, source_id: str) -> None:
        if licence not in ALLOWED:
            raise ValueError(f"{file}: licence {licence} may not ship")
        self.rows[file] = {
            "file": file,
            "asset": asset_id,
            "licence": licence,
            "author": author or "unknown",
            "sourceUrl": source_url or "",
            "upstream": source_id,
            "attributionRequired": licence != "CC0-1.0",
        }

    def add_data(self, files: list[str], asset_id: str, source_id: str) -> None:
        """Register converted MakeHuman/MPFB core data (CC0 since 2020)."""
        sources = {s["id"]: s for s in json.loads((COMPILER_DIR / "sources.json").read_text("utf-8"))["sources"]}
        src = sources[source_id]
        for f in files:
            self.add(f, asset_id, "CC0-1.0", "MakeHuman team / Data Collection AB", src["homepage"], source_id)

    def write(self) -> None:
        missing = []
        for path in sorted(ASSETS_CORE.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(ASSETS_CORE).as_posix()
            if rel in ("LICENSES.json", "manifest.json") or rel.endswith("_report.json") or rel == "catalog_skipped.json":
                continue
            if rel == "catalog.json" or rel.startswith("app/"):
                # Generated by PS2CC itself (no third-party content).
                self.rows.setdefault(rel, {"file": rel, "asset": "ps2cc:generated", "licence": "CC0-1.0", "author": "PS2CC",
                                           "sourceUrl": "", "upstream": "ps2cc", "attributionRequired": False})
            if rel not in self.rows:
                missing.append(rel)
            else:
                self.rows[rel]["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
                self.rows[rel]["bytes"] = path.stat().st_size
        if missing:
            raise RuntimeError(f"{len(missing)} shipped files have no licence row, e.g. {missing[:5]}")
        stale = [r for r in self.rows if not (ASSETS_CORE / r).exists()]
        for r in stale:
            del self.rows[r]
        out = {
            "format": "ps2cc.licenses/1",
            "policy": "Art and data: only CC0-1.0, CC-BY-4.0 and CC-BY-3.0 (with attribution). Bundled runtime software: Apache-2.0 with its notice (vendor/).",
            "files": [self.rows[k] for k in sorted(self.rows)],
        }
        (ASSETS_CORE / "LICENSES.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
        print(f"  licences: {len(self.rows)} files recorded")
